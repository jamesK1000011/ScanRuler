// G-code laid out as each slicer writes it — the header, the settings
// block, the lines at a layer change, the first moves of a layer — written
// for the pause tests from G-code those slicers produced: PrusaSlicer 2.9
// (";LAYER_CHANGE", ";Z:", ";HEIGHT:", ";BEFORE_LAYER_CHANGE" and
// ";AFTER_LAYER_CHANGE", its settings at the end), OrcaSlicer 2.2 for a
// Klipper printer (";LAYER_CHANGE", "SET_PRINT_STATS_INFO"), and Bambu
// Studio 2.4 for an A1 mini ("; CHANGE_LAYER", "; Z_HEIGHT:", "M991", the
// lift as a G3 arc, its settings in a block at the top). The moves are a
// square per layer.

const r3 = (x) => Math.round(x * 1000) / 1000
const fmt = (x) => String(r3(x)).replace(/^0\./, '.')

/** The Z of each layer's top: the first, then every other at height. */
export const zs = (layers, first, height) => Array.from({ length: layers }, (_, i) => r3(first + i * height))

const square = (e = '.03') => [`G1 X100 Y100 E${e}`, `G1 X120 Y100 E${e}`, `G1 X120 Y120 E${e}`, `G1 X100 Y120 E${e}`]

export function prusaGcode({ layers = 20, first = 0.2, height = 0.2, flavor = 'marlin2', pause = 'M601', model = 'MK4S', eol = '\n', binary = false } = {}) {
  if (binary) return Buffer.concat([Buffer.from('GCDE'), Buffer.alloc(60)])
  const out = ['; generated by PrusaSlicer 2.9.0+linux-x64 on 2026-11-01 at 10:00:00 UTC', '', '; external perimeters extrusion width = 0.45mm', '', 'M73 P0 R10', 'M201 X4000 Y4000 Z200 E2500', 'G90', 'M83', 'G28', 'G1 Z.2 F720']
  let prev = 0
  for (const z of zs(layers, first, height)) {
    out.push(';LAYER_CHANGE', `;Z:${r3(z)}`, `;HEIGHT:${r3(z - prev)}`, ';BEFORE_LAYER_CHANGE', 'G92 E0.0', `;${r3(z)}`, '', '', 'G1 E-.8 F2100', ';WIPE_START', 'G1 F7200', 'G1 X101 Y101 E-.2', ';WIPE_END', `G1 Z${fmt(z)} F720`, ';AFTER_LAYER_CHANGE', `;${r3(z)}`, 'G1 X100 Y100 F14400', 'G1 E.8 F2100', ';TYPE:External perimeter', ';WIDTH:0.45', ...square())
    prev = z
  }
  out.push('M107', 'G1 Z30 F720', 'M84', '', '; filament used [mm] = 12.34', '; filament used [g] = 0.04', '; estimated printing time (normal mode) = 4m 10s', '', '; prusaslicer_config = begin', `; first_layer_height = ${first}`, `; gcode_flavor = ${flavor}`, `; layer_height = ${height}`, `; pause_print_gcode = ${pause}`, `; printer_model = ${model}`, '; prusaslicer_config = end', '')
  return out.join(eol)
}

export function orcaKlipperGcode({ layers = 20, first = 0.2, height = 0.2, pause = 'PAUSE' } = {}) {
  const out = ['; HEADER_BLOCK_START', '; generated by OrcaSlicer 2.2.0 on 2026-11-01 at 10:00:00', `; total layer number: ${layers}`, '; HEADER_BLOCK_END', '', '; CONFIG_BLOCK_START', `; gcode_flavor = klipper`, `; initial_layer_print_height = ${first}`, `; layer_height = ${height}`, `; machine_pause_gcode = ${pause}`, '; printer_model = Voron 2.4 350', '; CONFIG_BLOCK_END', '', '; EXECUTABLE_BLOCK_START', 'M83', 'PRINT_START EXTRUDER=215 BED=60', 'G90']
  let prev = 0
  zs(layers, first, height).forEach((z, i) => {
    out.push(';LAYER_CHANGE', `;Z:${r3(z)}`, `;HEIGHT:${r3(z - prev)}`, `SET_PRINT_STATS_INFO CURRENT_LAYER=${i + 1}`, 'G1 E-.8 F1800', `G1 Z${fmt(z + 0.4)} F600`, 'G1 X100 Y100 F30000', `G1 Z${fmt(z)}`, 'G1 E.8 F1800', '; FEATURE: Outer wall', ...square())
    prev = z
  })
  out.push('PRINT_END', '; EXECUTABLE_BLOCK_END', '')
  return out.join('\n')
}

export function bambuGcode({ layers = 20, first = 0.2, height = 0.2 } = {}) {
  const out = ['; HEADER_BLOCK_START', '; BambuStudio 02.04.00.70', '; model printing time: 3m 1s; total estimated time: 9m 32s', `; total layer number: ${layers}`, '; total filament length [mm] : 12.34', '; total filament weight [g] : 0.04', '; HEADER_BLOCK_END', '', '; CONFIG_BLOCK_START', '; gcode_flavor = marlin', `; initial_layer_print_height = ${first}`, `; layer_height = ${height}`, '; layer_change_gcode = ; layer num/total_layer_count: {layer_num+1}/[total_layer_count]\\nM73 L{layer_num+1}\\nM991 S0 P{layer_num} ;notify layer change\\n', '; machine_pause_gcode = M400 U1', '; printer_model = Bambu Lab A1 mini', '; CONFIG_BLOCK_END', '', '; EXECUTABLE_BLOCK_START', 'M73 P0 R9', 'G90', 'M83']
  let prev = 0
  zs(layers, first, height).forEach((z, i) => {
    out.push('; CHANGE_LAYER', `; Z_HEIGHT: ${r3(z)}`, `; LAYER_HEIGHT: ${r3(z - prev)}`, 'G1 E-.8 F1800', `; layer num/total_layer_count: ${i + 1}/${layers}`, '; update layer progress', `M73 L${i + 1}`, `M991 S0 P${i} ;notify layer change`, 'G17', `G3 Z${fmt(z + 0.4)} I1.217 J0 P1  F30000`, 'G1 X100 Y100', `G1 Z${fmt(z)}`, 'G1 E.8 F1800', '; FEATURE: Outer wall', ...square())
    prev = z
  })
  out.push('M991 S0 P-1 ;end timelapse at safe pos', '; EXECUTABLE_BLOCK_END', '')
  return out.join('\n')
}
